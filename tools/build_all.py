"""Build every sprite for CHRONOMANCER.
Humans: the owner's Male/Female 64px base templates, dressed by tools/dress.py.
Bernard: tools/costume.bernard_ritual (the Hollow King frame wearing human skin).
usage: python3 tools/build_all.py <gif dir> <Step-Quest dir>"""
import sys, os, json, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
GIF, SQ = sys.argv[1], sys.argv[2]
OUT = os.path.join(ROOT, 'assets', 'sprites')
subprocess.check_call([sys.executable, os.path.join(HERE, 'dress.py'), GIF, OUT])
meta = json.load(open(os.path.join(OUT, '_dress_meta.json'))); os.remove(os.path.join(OUT, '_dress_meta.json'))
sys.path.insert(0, HERE); import costume
src = open(os.path.join(SQ, 'js/assets.js')).read()
J = json.loads(src[src.index('{', src.index('ASSETS')): src.rstrip().rstrip(';').rindex('}') + 1])
meta['bernard'] = costume.bernard_ritual(SQ, J, os.path.join(OUT, 'bernard.png'))
open(os.path.join(ROOT, 'js', '01-sprites.js'), 'w').write('/* generated by tools/build_all.py — do not edit */\nwindow.TM = window.TM || {};\nTM.SPR = ' + json.dumps(meta) + ';\n')
print('sprites:', len(meta))
